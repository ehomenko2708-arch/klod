PURPLE = "7B2FBE"
LIGHT_PURPLE = "F3E8FF"
WHITE = "FFFFFF"
DARK = "1A1A2E"
GRAY = "F8F8F8"

def header_style(cell, bg=PURPLE):
    cell.font = Font(bold=True, color=WHITE, size=11)
    cell.fill = PatternFill("solid", fgColor=bg)
    cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)

def subheader_style(cell):
    cell.font = Font(bold=True, color=DARK, size=10)
    cell.fill = PatternFill("solid", fgColor=LIGHT_PURPLE)
    cell.alignment = Alignment(horizontal="left", vertical="center", wrap_text=True)

def content_style(cell, bg=WHITE):
    cell.font = Font(size=10, color=DARK)
    cell.fill = PatternFill("solid", fgColor=bg)
    cell.alignment = Alignment(horizontal="left", vertical="top", wrap_text=True)

def set_border(cell):
    thin = Side(style="thin", color="DDDDDD")
    cell.border = Border(left=thin, right=thin, top=thin, bottom=thin)

